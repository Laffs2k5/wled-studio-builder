"""WLED's own effect engine for a virtual device, taken from a WLED checkout at build time.

    python3 virtual/virtual_wled.py WLED_CHECKOUT OUT_DIR

Writes OUT_DIR/ with what virtual/build.sh compiles next to our own wled.h and glue:
- copied whole: the effect engine (FX.cpp, FX_fcn.cpp, FX_2Dfcn.cpp, FXparticleSystem.cpp,
  colors.cpp, palettes.cpp, wled_math.cpp), the headers they include, and the bundled libraries
  they use (fastled_slim, ArduinoJson, TimeLib);
- `globals.h`: the WLED_GLOBAL declarations the engine reads, copied from WLED's wled.h by name;
- `util_extract.cpp`: the helpers the engine calls from util.cpp and led.cpp, by name, and the
  noise functions as one block (they bring their own #define and static helpers).

Nothing of WLED's is stored in this repository. A WLED release that renames something stops this
script with "not in the checkout": fix the lists, don't paste WLED's code here.
"""
from __future__ import annotations

import re
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "preview"))
from wled_colors import definitions  # noqa: E402

SOURCES = ["FX.cpp", "FX_fcn.cpp", "FX_2Dfcn.cpp", "FXparticleSystem.cpp", "colors.cpp", "palettes.cpp", "wled_math.cpp"]
HEADERS = ["FX.h", "FXparticleSystem.h", "const.h", "colors.h", "fcn_declare.h", "fontmanager.h", "prng.h",
           "pin_manager.h", "bus_manager.h", "NodeStruct.h", "wled_metadata.h"]
LIBRARIES = ["src/dependencies/fastled_slim", "src/dependencies/json", "src/dependencies/time"]
WEB_ONLY = ["src/dependencies/json/AsyncJson-v6.h"]       # replaced by an empty file
# the WLED_GLOBALs the engine reads (wled.h)
GLOBALS = ["arlsDisableGammaCorrection", "blendingStyle", "bri", "briOld", "briT", "busConfigs", "currentLedmap",
           "errorFlag", "gammaCorrectBri", "interfaceUpdateCallMode", "lastRandomIndex", "pDoc", "randomPaletteChangeTime",
           "realtimeOverride", "stateChanged", "useHarmonicRandomPalette", "useMainSegmentOnly", "realtimeMode",
           "realtimeRespectLedMaps", "briMultiplier", "briS", "paletteBlend", "localTime", "useAMPM", "gammaCorrectVal"]
UTIL_FUNCTIONS = ["beat88", "beat16", "beat8", "beatsin88_t", "beatsin16_t", "beatsin8_t", "get_random_wheel_index",
                  "hw_random", "simulateSound", "mapf", "hashInt", "utf8_decode", "utf8_strlen", "extractModeDefaults"]
LED_FUNCTIONS = ["scaledBri"]
UTIL_BLOCKS = [("#define PERLIN_SHIFT", "String computeSHA1")]   # (first line, first line after)
UTIL_DEFINES = ["UTF8_LEN"]
UTIL_ENUMS = ["UM_SoundSimulations"]


def _need(found: dict[str, int], where: str) -> None:
    missing = [n for n, c in found.items() if c == 0]
    if missing:
        raise SystemExit(f"{where}: not in the checkout: {', '.join(missing)}")


def globals_h(wled_h: str) -> str:
    lines, found = [], {}
    for name in GLOBALS:
        m = re.search(r"^\s*WLED_GLOBAL[^;\n]*\b" + re.escape(name) + r"\b[^;\n]*;.*$", wled_h, re.M)
        found[name] = 1 if m else 0
        if m:
            lines.append(m.group(0).strip())
    _need(found, "wled.h")
    return "// generated by virtual_wled.py from WLED's wled.h: the globals the effect engine reads\n" + "\n".join(lines) + "\n"


def util_extract(util: str, led: str) -> str:
    found, parts = {}, {}
    for name in UTIL_FUNCTIONS:
        defs = definitions(util, name)
        found[name] = len(defs)
        for d in defs:
            parts[util.index(d)] = d          # source order: helpers before their users
    _need(found, "util.cpp")
    led_parts = []
    for name in LED_FUNCTIONS:
        defs = definitions(led, name)
        _need({name: len(defs)}, "led.cpp")
        led_parts += defs
    lines = util.split("\n")
    blocks = []
    for first, after in UTIL_BLOCKS:
        try:
            a = next(i for i, l in enumerate(lines) if l.startswith(first))
            b = next(i for i, l in enumerate(lines) if i > a and l.startswith(after))
        except StopIteration:
            raise SystemExit(f"util.cpp: the block from {first!r} isn't in the checkout") from None
        blocks.append("\n".join(lines[a:b]))
    head = []
    for name in UTIL_DEFINES:
        m = re.search(r"^#define " + name + r"\b.*$", util, re.M)
        _need({name: 1 if m else 0}, "util.cpp")
        head.append(m.group(0))
    for name in UTIL_ENUMS:
        m = re.search(r"typedef enum " + name + r"\b[^{]*\{[^}]*\}[^;]*;", util, re.S)
        _need({name: 1 if m else 0}, "util.cpp")
        head.append(m.group(0))
    return ("// generated by virtual_wled.py: WLED's own helpers, copied by name from util.cpp and led.cpp\n"
            '#include "wled.h"\n\n' + "\n".join(head) + "\n\n" + "\n\n".join(parts[k] for k in sorted(parts)) + "\n\n"
            + "\n\n".join(led_parts) + "\n\n" + "\n\n".join(blocks) + "\n")


def generate(wled: Path, out: Path) -> None:
    src = wled / "wled00" if (wled / "wled00").is_dir() else wled
    out.mkdir(parents=True, exist_ok=True)
    for f in SOURCES + HEADERS:
        if not (src / f).exists():
            raise SystemExit(f"{f}: not in the checkout")
        shutil.copyfile(src / f, out / f)
    for lib in LIBRARIES:
        if (out / lib).exists():
            shutil.rmtree(out / lib)
        shutil.copytree(src / lib, out / lib)
    for f in WEB_ONLY:
        (out / f).write_text("// virtual WLED: web-only, not needed by the effect engine\n")
    (out / "globals.h").write_text(globals_h((src / "wled.h").read_text(encoding="utf-8")))
    (out / "util_extract.cpp").write_text(util_extract((src / "util.cpp").read_text(encoding="utf-8"),
                                                       (src / "led.cpp").read_text(encoding="utf-8")))


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    generate(Path(sys.argv[1]), Path(sys.argv[2]))
    print("virtual WLED sources written to", sys.argv[2])
