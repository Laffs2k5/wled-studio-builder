"""WLED's own effect engine for a virtual device, taken from a WLED checkout at build time.

    python3 virtual/virtual_wled.py WLED_CHECKOUT OUT_DIR

Writes OUT_DIR/ with what virtual/build.sh compiles next to our own wled.h and glue:
- copied whole: the effect engine (FX.cpp, FX_fcn.cpp, FX_2Dfcn.cpp, FXparticleSystem.cpp,
  colors.cpp, palettes.cpp, wled_math.cpp), the state code (presets.cpp, playlist.cpp, led.cpp),
  the headers they include, and the bundled libraries they use (fastled_slim, ArduinoJson,
  TimeLib, Toki);
- `globals.h`: wled.h's Button struct and its plain-data WLED_GLOBALs with their defaults, in
  wled.h's own #if structure (glue.cpp includes it a second time to define them);
- `json_extract.cpp`: json.cpp's state functions by name (state in and out, palettes, effect
  names), without its info, network and web parts;
- `file_extract.cpp`: file.cpp up to its web serving (the JSON-in-file code presets.cpp uses);
- `util_extract.cpp`: the helpers the engine calls from util.cpp, by name, and the
  noise functions as one block (they bring their own #define and static helpers).

Nothing of WLED's is stored in this repository. A WLED release that renames something stops this
script with "not in the checkout": fix the lists, don't paste WLED's code here.
"""
from __future__ import annotations

import re
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "preview"))
from wled_colors import definitions  # noqa: E402

SOURCES = ["FX.cpp", "FX_fcn.cpp", "FX_2Dfcn.cpp", "FXparticleSystem.cpp", "colors.cpp", "palettes.cpp", "wled_math.cpp",
           "presets.cpp", "playlist.cpp", "led.cpp"]       # the last three: presets, playlists, state changes
# json.cpp by name: state in and out, palettes, effect names (not its info, network or web parts)
JSON_PREAMBLE = ("#define JSON_PATH_STATE", "static bool deserializeSegment")   # its anonymous namespace
# file.cpp up to its web serving: the JSON-in-file engine presets.cpp uses
FILE_BLOCK_END = "bool handleFileRead"
JSON_FUNCTIONS = ["deserializeSegment", "deserializeState", "serializeSegment", "serializeState", "setPaletteColors",
                  "serializePalettes", "serializeModeNames"]
HEADERS = ["FX.h", "FXparticleSystem.h", "const.h", "colors.h", "fcn_declare.h", "fontmanager.h", "prng.h",
           "pin_manager.h", "bus_manager.h", "NodeStruct.h", "wled_metadata.h"]
LIBRARIES = ["src/dependencies/fastled_slim", "src/dependencies/json", "src/dependencies/time", "src/dependencies/toki"]
WEB_ONLY = ["src/dependencies/json/AsyncJson-v6.h"]       # replaced by an empty file
UTIL_FUNCTIONS = ["beat88", "beat16", "beat8", "beatsin88_t", "beatsin16_t", "beatsin8_t", "get_random_wheel_index",
                  "hw_random", "simulateSound", "mapf", "hashInt", "utf8_decode", "utf8_strlen", "extractModeDefaults",
                  "parseNumber", "getVal", "getBoolVal"]
UTIL_BLOCKS = [("#define PERLIN_SHIFT", "String computeSHA1")]   # (first line, first line after)
UTIL_DEFINES = ["UTF8_LEN"]
UTIL_ENUMS = ["UM_SoundSimulations"]


def _need(found: dict[str, int], where: str) -> None:
    missing = [n for n, c in found.items() if c == 0]
    if missing:
        raise SystemExit(f"{where}: not in the checkout: {', '.join(missing)}")


PLAIN = re.compile(r"^\s*WLED_GLOBAL\s+(const\s+|volatile\s+)?(bool|byte|char|int|unsigned|long|float|double|size_t|time_t|"
                   r"u?int(8|16|32|64)_t)\b")
# the non-plain globals the state code needs (the rest are network, DMX, MQTT…)
OTHER_GLOBALS = re.compile(r"^\s*WLED_GLOBAL\s+[^;]*\b(busConfigs|pDoc|realtimeIP|buttons|toki)\b")
SKIP_DEFINES = re.compile(r"^\s*#\s*(define|undef)\s+(WLED_GLOBAL|_INIT|_INIT_N|WLED_DEFINE_GLOBAL_VARS)\b")


def all_globals_h(wled_h: str) -> str:
    """Every plain-data WLED_GLOBAL of WLED's wled.h with its default, inside WLED's own #if
    structure (some exist per platform), and wled.h's own #defines (defaults use them). Network,
    DMX, MQTT and other objects are left out: a virtual device has none."""
    out = ["// generated by virtual_wled.py from WLED's wled.h: its plain-data globals, in its #if structure"]
    cont = False
    for line in wled_h.split("\n"):
        s = line.strip()
        if cont:                       # a #define continued over lines
            out.append(line)
            cont = s.endswith("\\")
            continue
        if s.startswith("#"):
            directive = s[1:].strip().split(" ")[0]
            if directive in ("if", "ifdef", "ifndef", "elif", "else", "endif"):
                out.append(line)
            elif directive == "define" and not SKIP_DEFINES.match(line) and "pragma" not in s:
                out.append(line)
                cont = s.endswith("\\")
            continue
        if (PLAIN.match(line) or OTHER_GLOBALS.match(line)) and ";" in line:
            out.append(line.split(";")[0] + ";")
    # wled.h's include guard goes: glue.cpp includes this a second time to define the globals
    guard = [i for i, l in enumerate(out) if l.strip() in ("#ifndef WLED_H", "#define WLED_H")]
    if len(guard) != 2:
        raise SystemExit("wled.h: no WLED_H include guard")
    last_endif = max(i for i, l in enumerate(out) if l.strip().startswith("#endif"))
    out = [l for i, l in enumerate(out) if i not in guard and i != last_endif]
    return "\n".join(out) + "\n"


def button_struct(wled_h: str) -> str:
    m = re.search(r"^struct Button \{.*?^\};", wled_h, re.M | re.S)
    if not m:
        raise SystemExit("wled.h: no struct Button")
    return m.group(0)


def json_extract(json_cpp: str) -> str:
    lines = json_cpp.split("\n")
    a = next(i for i, l in enumerate(lines) if l.startswith(JSON_PREAMBLE[0]))
    b = next(i for i, l in enumerate(lines) if l.startswith(JSON_PREAMBLE[1]))
    parts, found = {}, {}
    for name in JSON_FUNCTIONS:
        defs = definitions(json_cpp, name)
        found[name] = len(defs)
        for d in defs:
            parts[json_cpp.index(d)] = d
    _need(found, "json.cpp")
    return ("// generated by virtual_wled.py: WLED's json.cpp, its state functions by name\n"
            '#include "wled.h"\n\n' + "\n".join(lines[a:b]) + "\n\n" + "\n\n".join(parts[k] for k in sorted(parts)) + "\n")


def util_extract(util: str) -> str:
    found, parts = {}, {}
    for name in UTIL_FUNCTIONS:
        defs = definitions(util, name)
        found[name] = len(defs)
        for d in defs:
            parts[util.index(d)] = d          # source order: helpers before their users
    _need(found, "util.cpp")
    lines = util.split("\n")
    blocks = []
    for first, after in UTIL_BLOCKS:
        try:
            a = next(i for i, l in enumerate(lines) if l.startswith(first))
            b = next(i for i, l in enumerate(lines) if i > a and l.startswith(after))
        except StopIteration:
            raise SystemExit(f"util.cpp: the block from {first!r} isn't in the checkout") from None
        blocks.append("\n".join(lines[a:b]))
    head = []
    for name in UTIL_DEFINES:
        m = re.search(r"^#define " + name + r"\b.*$", util, re.M)
        _need({name: 1 if m else 0}, "util.cpp")
        head.append(m.group(0))
    for name in UTIL_ENUMS:
        m = re.search(r"typedef enum " + name + r"\b[^{]*\{[^}]*\}[^;]*;", util, re.S)
        _need({name: 1 if m else 0}, "util.cpp")
        head.append(m.group(0))
    return ("// generated by virtual_wled.py: WLED's own helpers, copied by name from util.cpp\n"
            '#include "wled.h"\n\n' + "\n".join(head) + "\n\n" + "\n\n".join(parts[k] for k in sorted(parts)) + "\n\n"
            + "\n\n".join(blocks) + "\n")


def generate(wled: Path, out: Path) -> None:
    src = wled / "wled00" if (wled / "wled00").is_dir() else wled
    out.mkdir(parents=True, exist_ok=True)
    for f in SOURCES + HEADERS:
        if not (src / f).exists():
            raise SystemExit(f"{f}: not in the checkout")
        shutil.copyfile(src / f, out / f)
    for lib in LIBRARIES:
        if (out / lib).exists():
            shutil.rmtree(out / lib)
        shutil.copytree(src / lib, out / lib)
    for f in WEB_ONLY:
        (out / f).write_text("// virtual WLED: web-only, not needed by the effect engine\n")
    wled_h = (src / "wled.h").read_text(encoding="utf-8")
    # included twice: declared by wled.h, defined by glue.cpp; the struct only once
    (out / "globals.h").write_text("#ifndef VIRTUAL_WLED_BUTTON\n#define VIRTUAL_WLED_BUTTON\n" + button_struct(wled_h)
                                   + "\n#endif\n\n" + all_globals_h(wled_h))
    (out / "json_extract.cpp").write_text(json_extract((src / "json.cpp").read_text(encoding="utf-8")))
    file_cpp = (src / "file.cpp").read_text(encoding="utf-8")
    if FILE_BLOCK_END not in file_cpp:
        raise SystemExit(f"file.cpp: no {FILE_BLOCK_END!r} in the checkout")
    (out / "file_extract.cpp").write_text("// generated by virtual_wled.py: WLED's file.cpp up to its web serving\n"
                                          + file_cpp[:file_cpp.index(FILE_BLOCK_END)])
    (out / "util_extract.cpp").write_text(util_extract((src / "util.cpp").read_text(encoding="utf-8")))


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    generate(Path(sys.argv[1]), Path(sys.argv[2]))
    print("virtual WLED sources written to", sys.argv[2])
