"""WLED's own colour and palette code for the preview, taken from a WLED checkout at build time.

    python3 preview/wled_colors.py WLED_CHECKOUT OUT_DIR

Writes OUT_DIR/ with WLED's files the preview compiles in "exact colours" mode:
- copied whole: colors.h, palettes.cpp (the palettes, pure data) and fastled_slim (with its licence);
- `wled_colors.cpp`: the pure colour functions from colors.cpp and the Segment methods effects see
  (loadPalette, color_from_palette, color_wheel, fill, the fades, blur) from FX_fcn.cpp, copied
  verbatim by name, and the palette names;
- `wled_colors_prelude.h`: the palette constants from const.h, NUM_COLORS and BLACK from FX.h, and
  stand-ins for the Arduino bits.

Nothing of WLED's is kept in this repository: the files are generated from the user's checkout,
like the firmware itself. The shim (shim/wled.h) gives its Segment the members these bodies use.
"""
from __future__ import annotations

import re
import shutil
import sys
from pathlib import Path

# Functions taken from colors.cpp: the pure colour maths (not the file and JSON parts).
COLOR_FUNCTIONS = ["color_blend", "color_add", "color_fade", "adjust_color", "ColorFromPalette",
                   "generateHarmonicRandomPalette", "generateRandomPalette", "hsv2rgb_spectrum", "rgb2hsv"]
# Segment methods taken from FX_fcn.cpp.
SEGMENT_METHODS = ["loadPalette", "color_from_palette", "color_wheel", "fill", "fade_out",
                   "fadeToSecondaryBy", "fadeToBlackBy", "blur"]
DEFINES = ["NUM_COLORS", "BLACK"]   # simple #defines from FX.h
CONSTANTS = ["FASTLED_PALETTE_COUNT", "GRADIENT_PALETTE_COUNT", "DYNAMIC_PALETTE_COUNT",
             "FIXED_PALETTE_COUNT", "WLED_USERMOD_PALETTE_ID_BASE", "WLED_CUSTOM_PALETTE_ID_BASE"]

_TOKEN = re.compile(r'"(?:\\.|[^"\\\n])*"|\'(?:\\.|[^\'\\\n])*\'|//[^\n]*|/\*.*?\*/', re.S)
_RAW = re.compile(r'R"([^(\s]*)\((.*?)\)\1"', re.S)


def blank(text: str) -> str:
    """Comments, strings and character literals replaced by spaces of the same length (newlines
    kept), so braces and names can be found by position in the original text."""
    def spaces(m: re.Match) -> str:
        return re.sub(r"[^\n]", " ", m.group(0))
    return _TOKEN.sub(spaces, _RAW.sub(spaces, text))


def definitions(text: str, name: str) -> list[str]:
    """Every top-level function definition called `name` (or `Class::name`), verbatim: from the
    start of its line to its closing brace."""
    plain = blank(text)
    depth, out, i = 0, [], 0
    pattern = re.compile(r"\b" + re.escape(name) + r"\s*\(")
    while i < len(plain):
        ch = plain[i]
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
        elif depth == 0:
            m = pattern.match(plain, i)
            if m and (i == 0 or not (plain[i - 1].isalnum() or plain[i - 1] == "_")):
                end = re.search(r"[;{]", plain[m.end():])
                if end and end.group(0) == "{":
                    start = plain.rfind("\n", 0, i) + 1
                    brace = m.end() + end.start()
                    d, j = 0, brace
                    while True:
                        if plain[j] == "{":
                            d += 1
                        elif plain[j] == "}":
                            d -= 1
                            if d == 0:
                                break
                        j += 1
                    out.append(text[start:j + 1])
                    i = j + 1
                    continue
        i += 1
    return out


def constants(const_h: str) -> list[str]:
    out = []
    for name in CONSTANTS:
        m = re.search(r"^\s*constexpr\s+[\w\s]+\b" + name + r"\s*=[^;]*;", const_h, re.M)
        if not m:
            raise SystemExit(f"const.h: no {name}")
        out.append(m.group(0).strip())
    return out


def defines(fx_h: str) -> list[str]:
    out = []
    for name in DEFINES:
        m = re.search(r"^\s*#define\s+" + name + r"\b[^\n]*", fx_h, re.M)
        if not m:
            raise SystemExit(f"FX.h: no {name}")
        out.append(m.group(0).strip())
    return out


def palette_names(fx_fcn: str) -> str:
    m = re.search(r'const char JSON_palette_names\[\]\s*PROGMEM\s*=\s*R"=====\((.*?)\)=====";', fx_fcn, re.S)
    if not m:
        raise SystemExit("FX_fcn.cpp: no JSON_palette_names")
    return m.group(1)


PGMSPACE = """// generated by wled_colors.py: the Arduino flash-memory helpers, as plain memory
#pragma once
#include <string.h>
#include <stdint.h>
#ifndef PROGMEM
#define PROGMEM
#endif
#define pgm_read_byte(a) (*(const uint8_t*)(a))
#define pgm_read_word(a) (*(const uint16_t*)(a))
#define pgm_read_dword(a) (*(const uint32_t*)(a))
#define memcpy_P memcpy
"""


def generate(wled: Path, out: Path) -> dict:
    src = wled / "wled00" if (wled / "wled00").is_dir() else wled
    colors_cpp = (src / "colors.cpp").read_text(encoding="utf-8")
    fx_fcn = (src / "FX_fcn.cpp").read_text(encoding="utf-8")
    const_h = (src / "const.h").read_text(encoding="utf-8")
    fx_h = (src / "FX.h").read_text(encoding="utf-8")
    out.mkdir(parents=True, exist_ok=True)
    fl = out / "src" / "dependencies" / "fastled_slim"
    fl.mkdir(parents=True, exist_ok=True)
    for f in ("fastled_slim.h", "fastled_slim.cpp", "LICENSE.txt"):
        shutil.copyfile(src / "src" / "dependencies" / "fastled_slim" / f, fl / f)
    shutil.copyfile(src / "colors.h", out / "colors.h")
    shutil.copyfile(src / "palettes.cpp", out / "palettes.cpp")
    (out / "pgmspace.h").write_text(PGMSPACE)
    (out / "wled_colors_prelude.h").write_text(
        "// generated by wled_colors.py from WLED's const.h: what colors.h and the palette code need\n"
        "#pragma once\n#include <stddef.h>\n#include <stdint.h>\n#include <pgmspace.h>\n"
        "typedef uint8_t byte;\n#define IRAM_ATTR\n#define WLED_O2_ATTR\n#define WLED_O3_ATTR\n"
        "#define WLED_DISABLE_2D\n" + "\n".join(constants(const_h) + defines(fx_h)) + "\n")
    parts, found = [], {}
    for name in COLOR_FUNCTIONS:
        defs = definitions(colors_cpp, name)
        found[name] = len(defs)
        parts += defs
    for name in SEGMENT_METHODS:
        defs = definitions(fx_fcn, "Segment::" + name)
        found["Segment::" + name] = len(defs)
        parts += defs
    missing = [n for n, c in found.items() if c == 0]
    if missing:
        raise SystemExit(f"not found in the checkout: {', '.join(missing)}")
    names = palette_names(fx_fcn)
    (out / "wled_colors.cpp").write_text(
        "// generated by wled_colors.py: WLED's own code, copied by name from the checkout\n"
        '#include "wled.h"\n\n'
        "std::vector<CRGBPalette16> customPalettes;\nstd::vector<UsermodPalette> usermodPalettes;\n"
        f'extern const char JSON_palette_names[];\nconst char JSON_palette_names[] = R"=====({names})=====";\n\n'
        + "\n\n".join(parts) + "\n")
    return found


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    print("wled colours:", generate(Path(sys.argv[1]), Path(sys.argv[2])))
